#include <stdint.h>

#include "psa/crypto.h"
#include "psa/crypto_extra.h"
#include "psa_test_support.h"
#include "aes_ecb.h"
#include "unity.h"

void setUp(void)
{
    TEST_ASSERT_EQUAL(PSA_SUCCESS, psa_crypto_init());
}

void tearDown(void)
{
    mbedtls_psa_crypto_free();
}

void test_psa_aes_encrypt_ecb(void)
{
    const uint8_t key[] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    const uint8_t in[]  = {0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a};
    const uint8_t out[] = {0x3a, 0xd7, 0x7b, 0xb4, 0x0d, 0x7a, 0x36, 0x60, 0xa8, 0x9e, 0xca, 0xf3, 0x24, 0x66, 0xef, 0x97};
    uint8_t buffer[16];

    TEST_ASSERT_EQUAL(SL_STATUS_OK, crypto_aes_ecb_encrypt(key, in, buffer));
    TEST_ASSERT_EQUAL_UINT8_ARRAY(out, buffer, 16);
}

void test_psa_aes_encrypt_ecb_reinitializes_after_psa_free(void)
{
    const uint8_t key[] = {0x2b, 0x7e, 0x15, 0x16, 0x28, 0xae, 0xd2, 0xa6, 0xab, 0xf7, 0x15, 0x88, 0x09, 0xcf, 0x4f, 0x3c};
    const uint8_t in[]  = {0x6b, 0xc1, 0xbe, 0xe2, 0x2e, 0x40, 0x9f, 0x96, 0xe9, 0x3d, 0x7e, 0x11, 0x73, 0x93, 0x17, 0x2a};
    const uint8_t out[] = {0x3a, 0xd7, 0x7b, 0xb4, 0x0d, 0x7a, 0x36, 0x60, 0xa8, 0x9e, 0xca, 0xf3, 0x24, 0x66, 0xef, 0x97};
    uint8_t buffer[16];

    TEST_ASSERT_EQUAL(SL_STATUS_OK, crypto_aes_ecb_encrypt(key, in, buffer));
    mbedtls_psa_crypto_free();

    TEST_ASSERT_EQUAL(SL_STATUS_OK, crypto_aes_ecb_encrypt(key, in, buffer));
    TEST_ASSERT_EQUAL_UINT8_ARRAY(out, buffer, 16);
}

