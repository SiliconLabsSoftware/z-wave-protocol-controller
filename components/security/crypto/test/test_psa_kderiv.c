#include <stdint.h>

#include "kderiv.h"
#include "psa/crypto.h"
#include "psa/crypto_extra.h"
#include "unity.h"

void setUp(void)
{
    TEST_ASSERT_EQUAL(PSA_SUCCESS, psa_crypto_init());
}

void tearDown(void)
{
    mbedtls_psa_crypto_free();
}

void test_psa_key_derivation(void)
{
    uint8_t network_key[16]                 = {0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f};
    uint8_t pseudo_random_keymat_output[16] = {0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f};
    uint8_t ccm_key[16];
    uint8_t mpan_key[16];
    uint8_t pers_string[32];
    const uint8_t auth_tag[64]          = {0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f,
                                           0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f, 0x48, 0x49, 0x4a, 0x4b, 0x4c, 0x4d, 0x4e, 0x4f};
    const uint8_t ecdh_share_secret[32] = {0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47, 0x40, 0x41, 0x42, 0x43, 0x44, 0x45, 0x46, 0x47};

    const uint8_t py_ccm_key[16]     = {0xaf, 0x7f, 0x0a, 0x1e, 0xfc, 0xfe, 0x8f, 0x4b, 0x1f, 0xd2, 0x84, 0x5d, 0xd2, 0x85, 0x6f, 0x7d};
    const uint8_t py_pers_string[32] = {0xcc, 0xf8, 0xb4, 0x2a, 0x4f, 0x70, 0x21, 0x76, 0xac, 0x2b, 0x91, 0x94, 0xdb, 0xbd, 0xb8, 0x2c, 0x47, 0x43, 0x02, 0xff, 0x12, 0xe1, 0xe8, 0x26, 0x64, 0x22, 0xf3, 0xac, 0x44, 0x89, 0x4b, 0x87};
    const uint8_t py_mpan_key[16]    = {0xb8, 0x9d, 0xb1, 0x54, 0x3f, 0xd2, 0x82, 0x0e, 0xa9, 0x79, 0xc9, 0x6a, 0x30, 0x5a, 0x23, 0x0b};

    const uint8_t py_temp_ccm_key[16]                = {0x47, 0xda, 0x9d, 0x15, 0x39, 0xec, 0x73, 0xe5, 0xd2, 0xa0, 0xf7, 0x37, 0xdb, 0xf2, 0x9b, 0x33};
    const uint8_t py_temp_pers_string[32]            = {0x94, 0xa5, 0x3e, 0xb9, 0xa1, 0x2d, 0x7c, 0xd9, 0x49, 0xea, 0x70, 0xff, 0xb8, 0xa6, 0xe7, 0x1e, 0xa6, 0xf7, 0x9c, 0xa7, 0xa0, 0x14, 0x5a, 0x08, 0xba, 0xd5, 0x82, 0xae, 0xb0, 0x9b, 0xd2, 0x8b};
    const uint8_t py_temp_mpan_key[16]               = {0xc2, 0x8e, 0x57, 0x5f, 0x24, 0x6f, 0x59, 0xa4, 0xa5, 0x85, 0x0f, 0x20, 0x66, 0xf1, 0x06, 0x2b};
    const uint8_t py_pseudo_random_keymat_output[16] = {0x74, 0x77, 0x8f, 0x89, 0xd4, 0xd8, 0x8c, 0x6e, 0x46, 0x59, 0x63, 0x4a, 0x88, 0xea, 0x98, 0x7a};

    networkkey_expand(0, network_key, ccm_key, pers_string, mpan_key);
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_ccm_key, ccm_key, 16, "ccm_key");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_pers_string, pers_string, 32, "pers_string");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_mpan_key, mpan_key, 16, "mpan_key");

    tempkey_extract(ecdh_share_secret, auth_tag, pseudo_random_keymat_output);
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_pseudo_random_keymat_output, pseudo_random_keymat_output, 16, "prk");

    tempkey_expand(0, pseudo_random_keymat_output, ccm_key, pers_string, mpan_key);
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_temp_ccm_key, ccm_key, 16, "temp ccm_key");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_temp_pers_string, pers_string, 32, "temp pers_string");
    TEST_ASSERT_EQUAL_UINT8_ARRAY_MESSAGE(py_temp_mpan_key, mpan_key, 16, "temp mpan_key");
}
